    /// Limit tags per category
    fn limit_tags_per_category(&self, result: &mut TaggingResult) {
        let mut category_counts: HashMap<TagCategory, usize> = HashMap::new();
        
        result.tags.retain(|tag| {
            let count = category_counts.entry(tag.category).or_insert(0);
            if *count < self.config.max_tags_per_category {
                *count += 1;
                true
            } else {
                false
            }
        });
    }
    
    /// Merge tagging results
    pub fn merge_results(&self, results: &[TaggingResult]) -> TaggingResult {
        let mut merged = TaggingResult::new("merged");
        
        for result in results {
            for tag in &result.tags {
                // Check if tag already exists
                if let Some(existing) = merged.tags.iter_mut().find(|t| t.tag == tag.tag && t.category == tag.category) {
                    existing.merge(tag);
                } else {
                    merged.add_tag(tag.clone());
                }
            }
            
            merged.frames_analyzed += result.frames_analyzed;
            merged.notes.extend(result.notes.clone());
        }
        
        merged.sort_by_confidence();
        merged
    }
    
    /// Get known tags for autocomplete
