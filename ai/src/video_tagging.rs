/// Extract year from string using simple pattern matching
fn regex_match_year(s: &str) -> Option<String> {
    // Look for 4-digit year between 1900-2099
    for i in 0..s.len().saturating_sub(3) {
        let substr = &s[i..i+4];
        if let Ok(year) = substr.parse::<u32>() {
            if year >= 1900 && year <= 2099 {
                // Check it's not part of a larger number
                let prev_char = if i > 0 { s.chars().nth(i-1) } else { None };
                let next_char = s.chars().nth(i+4);
                
                if prev_char.map(|c| !c.is_ascii_digit()).unwrap_or(true) &&
                   next_char.map(|c| !c.is_ascii_digit()).unwrap_or(true) {
                    return Some(substr.to_string());
                }
            }
        }
    }
    None
}

