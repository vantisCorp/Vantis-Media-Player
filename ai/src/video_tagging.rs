/// Video tag category
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum TagCategory {
    /// Content type (movie, series, documentary, etc.)
    ContentType,
    /// Genre tags
    Genre,
    /// Visual elements
    Visual,
    /// Audio elements
    Audio,
    /// People/actors
    People,
    /// Locations
    Location,
    /// Activities
    Activity,
    /// Objects
    Object,
    /// Mood/atmosphere
    Mood,
    /// Technical quality
    Technical,
    /// Custom user tag
    Custom,
}

impl TagCategory {
    /// Get display name
    pub fn display_name(&self) -> &'static str {
        match self {
            Self::ContentType => "Content Type",
            Self::Genre => "Genre",
            Self::Visual => "Visual",
            Self::Audio => "Audio",
            Self::People => "People",
            Self::Location => "Location",
            Self::Activity => "Activity",
            Self::Object => "Objects",
            Self::Mood => "Mood",
            Self::Technical => "Technical",
            Self::Custom => "Custom",
        }
    }
}

/// Video tag with confidence score
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct VideoTag {
    /// Tag text
    pub tag: String,
    
    /// Category
    pub category: TagCategory,
    
    /// Confidence score (0.0 - 1.0)
    pub confidence: f32,
    
    /// Source of the tag
    pub source: TagSource,
    
    /// Timestamps where this tag appears (in seconds)
    pub timestamps: Vec<f64>,
    
    /// Is this tag verified by user
    pub verified: bool,
}

impl VideoTag {
    /// Create a new tag
    pub fn new(tag: &str, category: TagCategory, confidence: f32) -> Self {
        Self {
            tag: tag.to_string(),
            category,
            confidence,
            source: TagSource::AutoGenerated,
            timestamps: Vec::new(),
            verified: false,
        }
    }
    
    /// Add timestamp
    pub fn add_timestamp(&mut self, ts: f64) {
        if !self.timestamps.contains(&ts) {
            self.timestamps.push(ts);
        }
    }
    
    /// Merge with another tag
    pub fn merge(&mut self, other: &VideoTag) {
        // Average confidence
        self.confidence = (self.confidence + other.confidence) / 2.0;
        
        // Merge timestamps
        for ts in &other.timestamps {
            self.add_timestamp(*ts);
        }
    }
}

/// Source of a tag
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum TagSource {
    /// Auto-generated by AI
    AutoGenerated,
    /// From metadata
    Metadata,
    /// From user input
    UserInput,
    /// From external API (IMDb, TMDB, etc.)
    ExternalAPI,
    /// From filename
    Filename,
}

