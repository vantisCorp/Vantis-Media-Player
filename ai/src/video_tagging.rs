/// Result of video tagging
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TaggingResult {
    /// Video ID
    pub video_id: String,
    
    /// All tags
    pub tags: Vec<VideoTag>,
    
    /// Processing time in seconds
    pub processing_time: f32,
    
    /// Frames analyzed
    pub frames_analyzed: u32,
    
    /// Confidence threshold used
    pub confidence_threshold: f32,
    
    /// Warnings or notes
    pub notes: Vec<String>,
}

impl TaggingResult {
    /// Create a new result
    pub fn new(video_id: &str) -> Self {
        Self {
            video_id: video_id.to_string(),
            tags: Vec::new(),
            processing_time: 0.0,
            frames_analyzed: 0,
            confidence_threshold: 0.5,
            notes: Vec::new(),
        }
    }
    
    /// Add a tag
    pub fn add_tag(&mut self, tag: VideoTag) {
        self.tags.push(tag);
    }
    
    /// Get tags by category
    pub fn tags_by_category(&self, category: TagCategory) -> Vec<&VideoTag> {
        self.tags.iter().filter(|t| t.category == category).collect()
    }
    
    /// Get tags above confidence threshold
    pub fn high_confidence_tags(&self, threshold: f32) -> Vec<&VideoTag> {
        self.tags.iter().filter(|t| t.confidence >= threshold).collect()
    }
    
    /// Sort tags by confidence
    pub fn sort_by_confidence(&mut self) {
        self.tags.sort_by(|a, b| b.confidence.partial_cmp(&a.confidence).unwrap_or(std::cmp::Ordering::Equal));
    }
    
    /// Get unique tag values
    pub fn unique_tags(&self) -> HashSet<&str> {
        self.tags.iter().map(|t| t.tag.as_str()).collect()
    }
}

